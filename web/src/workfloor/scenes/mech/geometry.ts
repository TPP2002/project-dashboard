export function mechSvg(prefix: string) {
  // 横移归外层所有，部件的呼吸动画不能覆盖装配位置。
  const draw = (n: string) => { const p = byName[n]; return `<g transform="translate(${p.dx},0)"><g class="${clsFor(n, 'done')}" data-part="${n}">${p.build()}</g></g>` }
  // v9 的身体同相呼吸合为一个变换；头仍在 DRAW 的最上层单独摆动。
  return `<g class="mech idle" data-mech="${prefix}"><g data-body>${DRAW.filter(n => n !== 'head').map(draw).join('')}</g>${draw('head')}</g>`
}
export function bounds(pts: Points) {
  const x = Math.min(...pts.map(p => p[0])), y = Math.min(...pts.map(p => p[1]))
  return { x, y, width: Math.max(...pts.map(p => p[0])) - x, height: Math.max(...pts.map(p => p[1])) - y }
}
