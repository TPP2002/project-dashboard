import { v9 } from './palette'

export type Point = [number, number]
export type Points = Point[]
export type PartState = 'done' | 'off' | 'build' | 'pend' | 'block' | 'park'
export interface Part { name: string; main: Points; build: () => string; rings?: Points[]; dx: number }

const M = (pts: Points): Points => pts.map(([x, y]) => [400 - x, y])                 // 镜像到右半边
export const P = (pts: Points) => pts.map(p => p.join(',')).join(' ')
const pg = (pts: Points, g: string, cls = '') => `<polygon class="pl ${cls}" points="${P(pts)}" fill="url(#${g})"/>`
const hi = (pts: Points) => `<polygon class="hi" points="${P(pts)}"/>`
const sh = (pts: Points) => `<polygon class="sh" points="${P(pts)}"/>`
const ln = (pts: Points, cls = 'ln') => `<polyline class="${cls}" points="${P(pts)}"/>`
const riv = (x: number, y: number) => `<circle class="riv" cx="${x}" cy="${y}" r="1.7"/>`
const circ = (x: number, y: number, r: number, g: string, cls = 'pl') => `<circle class="${cls}" cx="${x}" cy="${y}" r="${r}" fill="url(#${g})"/>`
const hexPts = (cx: number, cy: number, r: number): Points => Array.from({ length: 6 }, (_, k) => { const a = Math.PI / 6 + k * Math.PI / 3; return [+(cx + Math.cos(a) * r).toFixed(1), +(cy + Math.sin(a) * r).toFixed(1)] })

/** 部件几何：名字 → { main: 主轮廓（焊缝沿它走）, svg(side) } ；side 为 'L' | 'R' | '' */
export const PARTS: Part[] = []
const shiftX = (pts: Points, dx: number): Points => pts.map(([x, y]) => [x + dx, y])
function part(name: string, main: Points, build: () => string, rings?: Points[], dx = 0) { PARTS.push({ name, main: shiftX(main, dx), build, rings: rings && rings.map(r => shiftX(r, dx)), dx }) }
function sided(name: string, main: Points, build: (mirror: (pts: Points) => Points, side: 'L' | 'R') => string, rings?: Points[], dx = 0) { part(name + 'L', main, () => build(p => p, 'L'), rings, -dx); part(name + 'R', M(main), () => build(M, 'R'), rings && rings.map(M), dx) }
export const seamD = (p: Part) => (p.rings || [p.main]).map(r => 'M' + P(r) + 'Z').join(' ')
export const clsFor = (n: string, st: PartState) => 'part ' + st + (n === 'head' ? ' head' : ' torso')

